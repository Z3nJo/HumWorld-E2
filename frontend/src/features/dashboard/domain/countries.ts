export function formatHumor(v: number | null): string {
  if (v == null) return '—';
  const sign = v > 0.0049 ? '+' : v < -0.0049 ? '−' : '±';
  return `${sign}${Math.abs(v).toFixed(2).replace('.', ',')}`;
}

export function formatNumber(n: number): string {
  return n.toLocaleString('es-CL');
}
